import { IMAGE_VERSION } from "@/lib/image-version";

export type CaseMeta = { label: string; value: string };

export type CaseMetric = { value: string; label: string; note?: string };

export type CaseVisual = {
  src?: string;
  alt: string;
  /** Tailwind‑класс соотношения сторон, по умолчанию 16/10 */
  aspect?: string;
  /** `contain` — для длинных скролл‑скриншотов, чтобы не обрезались */
  fit?: "cover" | "contain";
  caption?: string;
};

export type CaseSectionAlign = "left" | "right" | "center";

/**
 * Бенто‑сетка из 1–3 дополнительных изображений под блоком.
 * Один элемент рендерится крупно, как основное изображение секции.
 * Чтобы временно скрыть — поставьте `enabled: false`, данные можно не удалять.
 */
export type CaseGallery = {
  enabled?: boolean;
  /** `feature` — первый элемент занимает две колонки (по умолчанию), `equal` — равные колонки */
  layout?: "feature" | "equal";
  items: CaseVisual[];
};

export type CaseSection = {
  id: string;
  eyebrow: string;
  title: string;
  /** Продуктовое обоснование: почему так, а не иначе. Массив — отдельные абзацы */
  body: string | string[];
  align: CaseSectionAlign;
  /** `half` — текст и изображение поровну, `wide` — текст ~2/3 (по умолчанию 5/12 и 7/12) */
  textWidth?: "default" | "half" | "wide";
  /** Без `visual` текст занимает ~2/3 ширины и прижимается по `align` */
  visual?: CaseVisual;
  gallery?: CaseGallery;
};

export type CaseConstraint = { title: string; body: string };

export type CaseStudy = {
  slug: string;
  title: string;
  subtitle: string;
  meta: CaseMeta[];
  cover: CaseVisual;
  summary: {
    problem: string;
    solution: string;
    metrics: CaseMetric[];
  };
  sections: CaseSection[];
  constraints: CaseConstraint[];
  results: {
    lead: string;
    metrics: CaseMetric[];
    takeaway: string;
  };
};

