export function getCaseStudy(slug: string): CaseStudy | undefined {
  return caseStudies.find((c) => c.slug === slug);
}

export function getProjectForCase(slug: string): Project | undefined {
  return projects.find((p) => p.id === slug);
}

/** Соседние кейсы по кругу: после последнего идёт первый */
export function getAdjacentCases(slug: string): { prev: CaseStudy; next: CaseStudy } {
  const index = caseStudies.findIndex((c) => c.slug === slug);
  const count = caseStudies.length;
  return {
    prev: caseStudies[(index - 1 + count) % count],
    next: caseStudies[(index + 1) % count],
  };
}

export function caseHref(slug: string) {
  return `/work/${slug}`;
}
